HEADER = """\
# Simulink Editor shortcut overlays for PolyKybd (Windows, Linux and macOS).
# GENERATED by gen_specs.py from its table -- edit the table, not this file.
#
# Shortcuts: MathWorks, "Keyboard Shortcuts and Mouse Actions for Simulink
# Modeling" (R2026b). See SOURCES.md. Chosen by the window title on the MATLAB
# mapping entry: Simulink runs in the MATLAB process.
#
# Regenerate:
#   python polyhost/res/overlay_sources/simulink/fetch_icons.py
#   python polyhost/res/overlay_sources/simulink/gen_specs.py
#   python scripts/generate_app_overlays.py \\
#       polyhost/res/overlay_sources/simulink/bindings.yaml --preview /tmp/simulink_preview
app: simulink
match: [simulink]
output: simulink_template
icon_dir: icons
fit: contain
anchor: bottom-right
region: [36, 32]
margin: 0
mode: auto     # one rule per icon file: see HOUSE_LUMA_THRESHOLD in scripts/generate_app_overlays.py
threshold: 150

program_icon: simulink.png
program_icon_mode: alpha
program_icon_anchor: right
program_icon_region: [37, 32]
program_icon_margin: 0

bindings:
"""

# Labels that would fold onto a shared concept but mean something else here.
NOT_SHARED = {"Last viewed", "Next viewed", "Rename", "Comment out", "Build",
              "Stop", "Run"}


def main() -> int:
    chord_table.write(HERE / "bindings.yaml", HEADER, ROWS, NOT_SHARED)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
