HEADER = """\
# COMSOL Multiphysics shortcut overlays for PolyKybd (Windows, Linux and macOS).
# GENERATED by gen_specs.py from its table -- edit the table, not this file.
#
# Shortcuts: COMSOL Multiphysics Reference Manual 6.4, "Keyboard Shortcuts".
# See SOURCES.md.
#
# Regenerate:
#   python polyhost/res/overlay_sources/comsol/fetch_icons.py
#   python polyhost/res/overlay_sources/comsol/gen_specs.py
#   python scripts/generate_app_overlays.py \\
#       polyhost/res/overlay_sources/comsol/bindings.yaml --preview /tmp/comsol_preview
app: comsol
match: [comsol]
output: comsol_template
icon_dir: icons
fit: contain
anchor: bottom-right
region: [36, 32]
margin: 0
mode: auto     # one rule per icon file: see HOUSE_LUMA_THRESHOLD in scripts/generate_app_overlays.py
threshold: 150

program_icon: comsol.png
program_icon_mode: alpha
program_icon_anchor: right
program_icon_region: [37, 32]
program_icon_margin: 0

bindings:
"""

# Labels that would fold onto a shared concept but mean something else here.
NOT_SHARED = {"Previous node", "Next node", "Duplicate node", "Toggle comment",
              "Stop method", "Breakpoint",
              "Rename"}


def main() -> int:
    chord_table.write(HERE / "bindings.yaml", HEADER, ROWS, NOT_SHARED)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
