#!/usr/bin/env python3
"""Write the Thunderbird entry of overlay-mapping.poly.yaml, with the compose
window's title prefix in every language.

The compose window runs in the same process as the main window, so only its
title tells it apart: "Write: <subject> - Thunderbird" in English,
"Verfassen: <subject> - Thunderbird" in German. So the mapping lists that
prefix in every language Thunderbird ships, each pointing at the compose set.

Two steps, both run by hand:

    # 1. Read the prefixes from Thunderbird's translations (network) into
    #    compose_titles.yaml
    python polyhost/res/overlay_sources/thunderbird/gen_titles.py --fetch esr153
    # 2. Rewrite the generated block of the mapping from compose_titles.yaml
    python polyhost/res/overlay_sources/thunderbird/gen_titles.py

`--check` exits 1 when the mapping block differs from what step 2 would write;
`tests/res/thunderbird_titles_test.py` runs the same comparison.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
RES = HERE.parent.parent
TITLES_FILE = HERE / "compose_titles.yaml"
MAPPING_FILE = RES / "overlay-mapping.poly.yaml"
OVERLAY_DIR = RES / "overlays"
LOCALES = "https://raw.githubusercontent.com/thunderbird/thunderbird-desktop/{ref}/mail/locales/all-locales"
L10N = "https://raw.githubusercontent.com/thunderbird/thunderbird-l10n/main/{lang}/mail/{path}"
# The title string moved from a .properties file (153 ESR) to Fluent (159).
FTL = "messenger/messengercompose/messengercompose.ftl"
PROPERTIES = "chrome/messenger/messengercompose/composeMsgs.properties"

BEGIN = "# BEGIN generated by overlay_sources/thunderbird/gen_titles.py -- do not edit by hand\n"
END = "# END generated by overlay_sources/thunderbird/gen_titles.py\n"

# Every name the main window's process reports, lowercased (see SOURCES.md).
APP_NAMES = ("thunderbird,thunderbird-esr,thunderbird-beta,thunderbird-nightly,"
             "thunderbird-bin,org.mozilla.thunderbird,org.mozilla.thunderbird_esr,"
             "thunderbird beta,thunderbird daily,thunderbird_thunderbird")

# Platform -> suffix of the overlay set stem ("" is Windows).
PLATFORMS = {"windows": "", "macos": "_mac", "linux": "_linux"}

HEADER = """\
# Thunderbird (sources: overlay_sources/thunderbird/). The main window and the
# compose window are one process, so the compose window is told apart by its
# title, which starts "Write:" in English; the prefix is listed in every
# language Thunderbird ships (compose_titles.yaml). Any other title, and a
# window with no title, gets the main window's set.
"""


def _http_get(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "polykybd"})
    return urllib.request.urlopen(req, timeout=60).read().decode("utf-8")


def prefix_from_ftl(text: str) -> str | None:
    """The text before `{ $subject }` in `compose-window-title`."""
    m = re.search(r"^compose-window-title\s*=\s*(.*?)\{\s*\$subject\s*\}", text, re.M)
    return m.group(1).strip() if m else None


def prefix_from_properties(text: str) -> str | None:
    """The text before `%1$S` in `windowTitleWrite`."""
    m = re.search(r"^windowTitleWrite\s*=\s*(.*?)%1\$S", text, re.M)
    return m.group(1).strip() if m else None


def fetch(ref: str) -> dict:
    langs = [ln.strip() for ln in _http_get(LOCALES.format(ref=ref)).splitlines()
             if ln.strip() and not ln.startswith("#")]
    prefixes: dict[str, str] = {}
    missing: list[str] = []
    for lang in langs:
        found = None
        for path, parse in ((FTL, prefix_from_ftl), (PROPERTIES, prefix_from_properties)):
            try:
                found = parse(_http_get(L10N.format(lang=lang, path=path)))
            except urllib.error.HTTPError:
                found = None
            if found:
                break
        if found:
            prefixes[lang] = found
        else:
            missing.append(lang)
    return {"thunderbird_ref": ref, "languages": langs, "missing": missing,
            "prefixes": prefixes}


def title_keys(data: dict) -> list[str]:
    """The distinct prefixes, English first."""
    english = "Write:"
    return [english] + sorted(set(data["prefixes"].values()) - {english})


def _overlay(stem: str) -> str:
    tiers = ("", ".combo", ".extra", ".gui")
    files = [f"{stem}{t}.mods.png" for t in tiers
             if (OVERLAY_DIR / f"{stem}{t}.mods.png").exists()]
    if not files:
        raise FileNotFoundError(f"no overlay files for {stem}")
    return "[" + ", ".join(files) + "]"


def _entry(keys: list[str], platform: str, ind: int) -> list[str]:
    i = " " * ind
    suffix = PLATFORMS[platform]
    anchor = f"tb_compose{suffix}"
    lines = [f"{i}overlay: {_overlay('thunderbird_template' + suffix)}",
             f"{i}titles-startswith:"]
    for n, prefix in enumerate(keys):
        value = (f"&{anchor} {_overlay('thunderbird_compose_template' + suffix)}"
                 if n == 0 else f"*{anchor}")
        lines.append(f"{i}  {json.dumps(prefix, ensure_ascii=False)}: {{overlay: {value}}}")
    return lines


def render_block(data: dict) -> str:
    keys = title_keys(data)
    lines = [f"# Compose title prefixes from Thunderbird {data['thunderbird_ref']}, "
             f"{len(data['languages'])} languages."]
    if data.get("missing"):
        lines.append(f"# Not translated, so they show the English prefix: "
                     f"{', '.join(data['missing'])}.")
    lines.append(f"{APP_NAMES}:")
    lines += _entry(keys, "windows", 2)
    lines += ["  # A matched `os:` branch replaces the entry, so the title sub-map is",
              "  # repeated inside it.",
              "  os:"]
    for platform in ("macos", "linux"):
        lines.append(f"    {platform}:")
        lines += _entry(keys, platform, 6)
    return BEGIN + HEADER + "\n".join(lines) + "\n" + END


def split_mapping(text: str) -> tuple[str, str, str]:
    start = text.index(BEGIN)
    end = text.index(END, start) + len(END)
    return text[:start], text[start:end], text[end:]


def load_titles() -> dict:
    with open(TITLES_FILE, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--fetch", metavar="THUNDERBIRD_BRANCH",
                    help="read the prefixes for this branch's locales first (e.g. esr153)")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the mapping block is not what would be written")
    args = ap.parse_args()

    if args.fetch:
        data = fetch(args.fetch)
        with open(TITLES_FILE, "w", encoding="utf-8") as fh:
            fh.write("# Generated by gen_titles.py --fetch from Thunderbird's translations.\n")
            yaml.safe_dump(data, fh, allow_unicode=True, sort_keys=False)
        print(f"Wrote {TITLES_FILE.name}: {len(data['prefixes'])} of "
              f"{len(data['languages'])} languages, missing {data['missing']}")

    text = MAPPING_FILE.read_bytes().decode("utf-8")
    head, old, tail = split_mapping(text)
    new = render_block(load_titles())
    if args.check:
        if old != new:
            print("overlay-mapping.poly.yaml: the Thunderbird block is out of date; run gen_titles.py")
            return 1
        return 0
    MAPPING_FILE.write_bytes((head + new + tail).encode("utf-8"))
    print(f"Rewrote the Thunderbird block of {MAPPING_FILE.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
