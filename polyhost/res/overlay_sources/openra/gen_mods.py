#!/usr/bin/env python3
"""Write openra_cnc.yaml (Tiberian Dawn) and openra_d2k.yaml (Dune 2000) from
openra_ra.yaml.

All OpenRA mods share most of their default keys. Each copy changes the name,
the output file and the ESC mark, puts the mod's own keys (production tabs,
power down; mods/<mod>/hotkeys.yaml in OpenRA) in place of the Red Alert ones,
and puts the mod's game-art block (or none) in place of the Red Alert block
(everything from GAME_ASSETS on).

    python polyhost/res/overlay_sources/openra/gen_mods.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
MOD_KEYS = "  # Production tabs and power: each mod's own keys"
END_MOD_KEYS = "  # End of the mod keys"
GAME_ASSETS = "# Keys redrawn from the user's own Red Alert files"


def _tab(key, icon, label):
    return f'  - {{ key: {key}, icon: {icon}.png, label: "{label}" }}\n'


MODS = {
    "cnc": {
        "title": "Tiberian Dawn",
        "keys": [_tab("E", "tabstructures", "Production tab: buildings"),
                 _tab("R", "tabdefense", "Production tab: defenses"),
                 _tab("T", "tabinfantry", "Production tab: infantry"),
                 _tab("Y", "tabvehicles", "Production tab: vehicles"),
                 _tab("U", "tabaircraft", "Production tab: aircraft"),
                 _tab("PGUP", "prevtab", "Previous production tab"),
                 _tab("PGDN", "nexttab", "Next production tab")],
        "game_assets": "cnc_game_assets.yaml",
    },
    "d2k": {
        "title": "Dune 2000",
        "keys": [_tab("E", "tabstructures", "Production tab: buildings"),
                 _tab("R", "tabupgrade", "Production tab: upgrades"),
                 _tab("T", "tabinfantry", "Production tab: infantry"),
                 _tab("Y", "tablight", "Production tab: light vehicles"),
                 _tab("U", "tabaircraft", "Production tab: aircraft"),
                 _tab("I", "tabvehicles", "Production tab: tanks"),
                 _tab("O", "tabstarport", "Production tab: starport"),
                 _tab("X", "powerdown", "Power down")],
        "game_assets": "d2k_game_assets.yaml",
    },
}


def render(mod: str) -> str:
    """The text of openra_<mod>.yaml for the current openra_ra.yaml."""
    spec = MODS[mod]
    changes = {
        "app: openra_ra\n": f"app: openra_{mod}\n",
        "output: openra_ra_template\n": f"output: openra_{mod}_template\n",
        "program_icon: program_ra.png\n": f"program_icon: program_{mod}.png\n",
    }
    lines = (HERE / "openra_ra.yaml").read_text(encoding="utf-8").splitlines(keepends=True)
    out = ["# GENERATED by gen_mods.py from openra_ra.yaml -- edit that file, not this one.\n",
           f"# OpenRA, {spec['title']} mod.\n"]
    seen, in_keys = set(), False
    for line in lines:
        if line.startswith(GAME_ASSETS):
            seen.add(GAME_ASSETS)
            if spec["game_assets"]:
                out.append((HERE / spec["game_assets"]).read_text(encoding="utf-8"))
            else:
                while out and out[-1] == "\n":   # no blank line left at the end
                    out.pop()
            break
        if line.startswith(MOD_KEYS):
            seen.add(MOD_KEYS)
            in_keys = True
            out.append(line)
            out.extend(spec["keys"])
            continue
        if in_keys:
            if line.startswith(END_MOD_KEYS):
                seen.add(END_MOD_KEYS)
                in_keys = False
                out.append(line)
            continue
        if line in changes:
            seen.add(line)
            line = changes[line]
        out.append(line)
    missing = (set(changes) | {GAME_ASSETS, MOD_KEYS, END_MOD_KEYS}) - seen
    assert not missing, f"openra_ra.yaml no longer has: {missing}"
    return "".join(out)


def main() -> int:
    for mod in MODS:
        (HERE / f"openra_{mod}.yaml").write_text(render(mod), encoding="utf-8")
        print(f"openra_{mod}.yaml written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
