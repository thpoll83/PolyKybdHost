#!/usr/bin/env python3
"""Write the `kicad` entry of overlay-mapping.poly.yaml, with every language's
window titles.

KiCad translates its window titles ("board — Leiterplatteneditor" in German),
and the title is the only thing that tells its windows apart: the editors share
the `kicad` process, and `pcbnew` and `eeschema` each host several windows. So
the mapping lists the six window names in every language KiCad ships.

Two steps, both run by hand:

    # 1. Read the names from KiCad's translations (network) into window_titles.yaml
    python polyhost/res/overlay_sources/kicad/gen_titles.py --fetch 10.0.7
    # 2. Rewrite the generated block of the mapping from window_titles.yaml
    python polyhost/res/overlay_sources/kicad/gen_titles.py

`--check` exits 1 when the mapping block differs from what step 2 would write;
`tests/res/kicad_titles_test.py` runs the same comparison.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
RES = HERE.parent.parent
TITLES_FILE = HERE / "window_titles.yaml"
MAPPING_FILE = RES / "overlay-mapping.poly.yaml"
OVERLAY_DIR = RES / "overlays"
RAW = "https://gitlab.com/kicad/code/kicad/-/raw/{ref}/translation/pofiles/{name}"

BEGIN = "# BEGIN generated by overlay_sources/kicad/gen_titles.py -- do not edit by hand\n"
END = "# END generated by overlay_sources/kicad/gen_titles.py\n"

# Window -> (English name as in KiCad's source, overlay set stem, where the
# name is in the title). An editor's title ends in its name
# ("board — PCB Editor"); the 3D Viewer's starts with it ("3D Viewer — R_0402").
WINDOWS = {
    "pcb": ("PCB Editor", "kicad_pcb_template", "end"),
    "sch": ("Schematic Editor", "kicad_sch_template", "end"),
    "fp": ("Footprint Editor", "kicad_fp_template", "end"),
    "sym": ("Symbol Editor", "kicad_sym_template", "end"),
    "gerbview": ("Gerber Viewer", "kicad_gerbview_template", "end"),
    "3d": ("3D Viewer", "kicad_3d_template", "start"),
}

HEADER = """\
# KiCad (sources: overlay_sources/kicad/). Started from the project manager,
# every editor runs in the `kicad` process; started on its own, it is `pcbnew`,
# `eeschema` or `gerbview`, and `pcbnew` and `eeschema` each host several
# windows. So the windows are told apart by the title only: an editor's title
# ends in its name ("board — PCB Editor"), the 3D Viewer's starts with it. KiCad
# translates these names, so each one is listed in every language KiCad ships
# (window_titles.yaml). The `title` gate keeps the project manager and the other
# tools out, and fails when there is no window at all, so the macOS windowless
# path draws nothing rather than the PCB keys. The entry's own overlay is
# reached only by a window with an empty title (the gate is skipped then).
"""


def _http_get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "polykybd"})
    return urllib.request.urlopen(req, timeout=60).read()


def _unquote(s: str) -> str:
    return json.loads(s)


def parse_po(text: str) -> dict[str, str]:
    """msgid -> msgstr for the translated, non-fuzzy entries without a context."""
    out: dict[str, str] = {}
    for block in re.split(r"\n\s*\n", text):
        lines = [ln for ln in block.splitlines() if ln.strip()]
        if any(ln.startswith("#,") and "fuzzy" in ln for ln in lines):
            continue
        if any(ln.startswith("msgctxt") for ln in lines):
            continue
        field, parts = None, {"msgid": [], "msgstr": []}
        for ln in lines:
            if ln.startswith("#"):
                continue
            m = re.match(r'(msgid|msgstr)\s+(".*")$', ln)
            if m:
                field = m.group(1)
                parts[field].append(_unquote(m.group(2)))
            elif ln.startswith('"') and field in parts:
                parts[field].append(_unquote(ln))
            else:
                field = None
        msgid, msgstr = "".join(parts["msgid"]), "".join(parts["msgstr"]).strip()
        if msgid and msgstr:
            out[msgid] = msgstr
    return out


def fetch(ref: str) -> dict:
    linguas = _http_get(RAW.format(ref=ref, name="LINGUAS")).decode("utf-8")
    langs = [ln.strip() for ln in linguas.splitlines()
             if ln.strip() and not ln.lstrip().startswith("#")]
    names: dict[str, dict[str, str]] = {key: {} for key in WINDOWS}
    for lang in langs:
        table = parse_po(_http_get(RAW.format(ref=ref, name=f"{lang}.po")).decode("utf-8"))
        for key, (english, _stem, _where) in WINDOWS.items():
            local = table.get(english)
            if local and local != english:
                names[key][lang] = local
    return {"kicad_version": ref, "languages": langs, "names": names}


def title_keys(data: dict) -> dict[str, list[str]]:
    """Window -> its distinct names, English first. Raises when one name belongs
    to two windows: the title could then not tell them apart."""
    owner: dict[str, str] = {}
    keys: dict[str, list[str]] = {}
    for key, (english, _stem, _where) in WINDOWS.items():
        seen = [english] + sorted(set(data["names"].get(key, {}).values()) - {english})
        for name in seen:
            if owner.setdefault(name, key) != key:
                raise ValueError(f"{name!r} names both {owner[name]} and {key}")
        keys[key] = seen
    return keys


def _overlay(stem: str, mac: bool) -> str:
    base = stem + ("_mac" if mac else "")
    tiers = ("", ".combo", ".extra", ".gui")
    files = [f"{base}{t}.mods.png" for t in tiers
             if (OVERLAY_DIR / f"{base}{t}.mods.png").exists()]
    if not files:
        raise FileNotFoundError(f"no overlay files for {base}")
    return "[" + ", ".join(files) + "]"


def _escape(name: str) -> str:
    # re.escape also escapes spaces, which only makes the line harder to read.
    return re.escape(name).replace("\\ ", " ")


def _gate(keys: dict[str, list[str]]) -> str:
    ends = [_escape(n) for k, (_e, _s, w) in WINDOWS.items() if w == "end" for n in keys[k]]
    starts = [_escape(n) for k, (_e, _s, w) in WINDOWS.items() if w == "start" for n in keys[k]]
    return f"(?:{'|'.join(ends)})$|^(?:{'|'.join(starts)})"


def _entry(keys: dict[str, list[str]], mac: bool, ind: int) -> list[str]:
    """One entry. Each overlay list is written once as a YAML anchor, and every
    title key refers to it, so a window's name in 44 languages is 44 lines."""
    i = " " * ind
    anchor = {key: f"kicad_{key}{'_mac' if mac else ''}" for key in WINDOWS}
    lines = [f"{i}overlay: {_overlay(WINDOWS['pcb'][1], mac)}",
             f"{i}title: {json.dumps(_gate(keys), ensure_ascii=False)}"]
    defined: set[str] = set()
    for where, label in (("start", "titles-startswith"), ("end", "titles-endswith")):
        lines.append(f"{i}{label}:")
        for key, (_english, stem, w) in WINDOWS.items():
            if w != where:
                continue
            for name in keys[key]:
                if key in defined:
                    value = f"*{anchor[key]}"
                else:
                    value = f"&{anchor[key]} {_overlay(stem, mac)}"
                    defined.add(key)
                lines.append(f"{i}  {json.dumps(name, ensure_ascii=False)}: {{overlay: {value}}}")
    return lines


def render_block(data: dict) -> str:
    keys = title_keys(data)
    lines = [f"# Window names from KiCad {data['kicad_version']}, "
             f"{len(data['languages'])} languages."]
    lines.append("kicad,pcbnew,eeschema,gerbview:")
    lines += _entry(keys, mac=False, ind=2)
    lines += ["  # macOS: the Cmd sets. A matched `os:` branch replaces the entry, so the gate",
              "  # and the title sub-maps are repeated inside it.",
              "  os:", "    macos:"]
    lines += _entry(keys, mac=True, ind=6)
    return BEGIN + HEADER + "\n".join(lines) + "\n" + END


def split_mapping(text: str) -> tuple[str, str, str]:
    start = text.index(BEGIN)
    end = text.index(END, start) + len(END)
    return text[:start], text[start:end], text[end:]


def load_titles() -> dict:
    with open(TITLES_FILE, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--fetch", metavar="KICAD_TAG",
                    help="read the names from this KiCad tag's translations first")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the mapping block is not what would be written")
    args = ap.parse_args()

    if args.fetch:
        data = fetch(args.fetch)
        with open(TITLES_FILE, "w", encoding="utf-8") as fh:
            fh.write("# Generated by gen_titles.py --fetch from KiCad's translation/pofiles.\n")
            yaml.safe_dump(data, fh, allow_unicode=True, sort_keys=False)
        print(f"Wrote {TITLES_FILE.name}: {len(data['languages'])} languages")

    text = MAPPING_FILE.read_bytes().decode("utf-8")
    head, old, tail = split_mapping(text)
    new = render_block(load_titles())
    if args.check:
        if old != new:
            print("overlay-mapping.poly.yaml: the KiCad block is out of date; run gen_titles.py")
            return 1
        return 0
    MAPPING_FILE.write_bytes((head + new + tail).encode("utf-8"))
    print(f"Rewrote the KiCad block of {MAPPING_FILE.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
