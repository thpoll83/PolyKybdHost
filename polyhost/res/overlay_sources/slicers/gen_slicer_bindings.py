#!/usr/bin/env python3
"""Write one binding file per slicer from `keys.yaml`, and render them.

PrusaSlicer, Bambu Studio (a PrusaSlicer fork) and OrcaSlicer (a Bambu Studio
fork) share most of their shortcuts, so `keys.yaml` holds ONE table and marks
each row with the apps that bind it. This script selects each app's rows:

    bindings_prusaslicer.yaml             editor rows with `prusa`
    bindings_bambustudio.yaml             editor rows with `bambu`
    bindings_orcaslicer.yaml              editor rows with `orca`
    bindings_prusaslicer_gcodeviewer.yaml gcodeviewer rows (PrusaSlicer only)

Each file is then a normal spec for scripts/generate_app_overlays.py, which
writes the Windows/Linux set and, because the rows use CMDCTRL, the macOS set.
`--render` also runs the generator on each (`--preview DIR` writes its review
sheets to DIR/<app>/).

    python polyhost/res/overlay_sources/slicers/gen_slicer_bindings.py --render --preview /tmp/slicers_preview

Deterministic: the same keys.yaml writes byte-identical binding files.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[3]

# set name -> (section in keys.yaml, app tag, output stem, ESC mark, app title)
SETS = {
    "prusaslicer": ("editor", "prusa", "prusaslicer_template", "prusaslicer.png", "PrusaSlicer"),
    "bambustudio": ("editor", "bambu", "bambustudio_template", "bambustudio.png", "Bambu Studio"),
    "orcaslicer": ("editor", "orca", "orcaslicer_template", "orcaslicer.png", "OrcaSlicer"),
    "prusaslicer_gcodeviewer": ("gcodeviewer", "prusa", "prusa_gcodeviewer_template",
                                "prusa_gcodeviewer.png", "PrusaSlicer G-code Viewer"),
}

SPEC = {
    "icon_dir": "icons",
    "fit": "contain",
    "anchor": "bottom-right",
    "region": [36, 32],
    "margin": 0,
    "mode": "alpha",
    "threshold": 128,
    "program_icon_mode": "alpha",
    "program_icon_anchor": "right",
    "program_icon_region": [37, 32],
    "program_icon_margin": 0,
}

# Icons drawn 1-bit at 40x40 by fetch_icons.py (a glyph above a word, the
# spool, the brim ears). They are placed 1:1 so no line is rescaled away.
DRAWN_PREFIXES = ("view_", "paint_", "move_up_", "move_down_", "move_left_",
                  "move_right_", "fav_", "filament_")
DRAWN = {"spool", "brim_ears"}

HEADER = """\
# GENERATED by gen_slicer_bindings.py from keys.yaml -- edit those, not this file.
# {title}. Shortcut source: the app's keyboard-shortcuts dialog source; see
# SOURCES.md for the commits and what was left out.
"""


def _drawn(icon: str) -> bool:
    return icon in DRAWN or (icon.startswith(DRAWN_PREFIXES) and icon != "view_3d")


def bindings_for(rows: list[dict], app: str) -> list[dict]:
    out = []
    for r in rows:
        if app not in r["apps"]:
            continue
        b = {"key": r["key"]}
        if r.get("mods"):
            b["mods"] = list(r["mods"])
        if r.get("icon"):
            b["icon"] = f"{r['icon']}.png"
            if _drawn(r["icon"]):
                b.update({"region": [40, 40], "anchor": "right"})
        b["label"] = r["label"]
        for scope in ("only", "except"):
            if r.get(scope):
                b[scope] = list(r[scope])
        b["source"] = str(r["apps"][app])
        out.append(b)
    return out


def load_keys() -> dict:
    return yaml.safe_load((HERE / "keys.yaml").read_text(encoding="utf-8"))


def render(name: str, keys: dict) -> str:
    """The text of bindings_<name>.yaml (tests/res/slicer_bindings_test.py
    compares it with the committed file)."""
    section, app, output, mark, title = SETS[name]
    spec = dict(SPEC, app=name, match=[], output=output, program_icon=mark,
                bindings=bindings_for(keys[section], app))
    body = yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=200)
    return HEADER.format(title=title) + body


def write(name: str, keys: dict) -> Path:
    path = HERE / f"bindings_{name}.yaml"
    path.write_text(render(name, keys), encoding="utf-8")
    return path


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--render", action="store_true",
                    help="also run scripts/generate_app_overlays.py on each file")
    ap.add_argument("--preview", type=Path, help="preview directory (with --render)")
    args = ap.parse_args()
    keys = load_keys()
    for name in SETS:
        path = write(name, keys)
        print(f"wrote {path.relative_to(REPO_ROOT)}")
        if args.render:
            cmd = [sys.executable, str(REPO_ROOT / "scripts" / "generate_app_overlays.py"), str(path)]
            if args.preview:
                cmd += ["--preview", str(args.preview / name)]
            subprocess.run(cmd, check=True, cwd=REPO_ROOT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
