#!/usr/bin/env python3
"""Write civ4_classic.yaml (the base game and Warlords) from civ4_bts.yaml.

The base game and Warlords use Beyond the Sword's keys minus the ones Beyond
the Sword added or changed. This copies the Beyond the Sword spec, changes the
name, the app names it matches and the output file, and drops every binding
marked `classic: false`. SOURCES.md lists those bindings and why.

    python polyhost/res/overlay_sources/civ4/gen_classic.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
MARK = "classic: false"
CHANGES = {
    "app: civ4_bts\n": "app: civ4_classic\n",
    "output: civ4_bts_template\n": "output: civ4_classic_template\n",
}
MATCH = ("match: [civilization4, civ4warlords, civilization4.exe, civ4warlords.exe, "
         "steam_app_3900, steam_app_3990]\n")


def render() -> str:
    """The text of civ4_classic.yaml for the current civ4_bts.yaml."""
    lines = (HERE / "civ4_bts.yaml").read_text(encoding="utf-8").splitlines(keepends=True)
    out = ["# GENERATED by gen_classic.py from civ4_bts.yaml -- edit that file, not this one.\n",
           "# Civilization IV (Civilization4.exe) and Warlords (Civ4Warlords.exe): the\n",
           "# Beyond the Sword keys without the bindings marked `classic: false`.\n"]
    seen = set()
    dropped = 0
    for line in lines:
        if line.lstrip().startswith("- {") and MARK in line:
            dropped += 1
            continue
        if line.startswith("match:"):
            line = MATCH
            seen.add("match")
        elif line in CHANGES:
            seen.add(line)
            line = CHANGES[line]
        out.append(line)
    missing = ({"match"} | set(CHANGES)) - seen
    assert not missing, f"civ4_bts.yaml no longer has: {missing}"
    assert dropped, f"civ4_bts.yaml has no binding marked `{MARK}`"
    return "".join(out)


def main() -> int:
    (HERE / "civ4_classic.yaml").write_text(render(), encoding="utf-8")
    print("civ4_classic.yaml written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
