#!/usr/bin/env python3
"""Write the LabVIEW overlay spec from one table.

The keys are from NI's "LabVIEW Keyboard Shortcuts" page (LabVIEW User Manual,
updated 2026-09-28). The page lists Windows keys and says: "The Ctrl key in
these shortcuts corresponds to the (macOS) Option or Command key or to the
(Linux) Alt key." The menu commands use Command on macOS, so the macOS set has
Cmd where Windows has Ctrl, and the Linux set has Alt. The page names its own
macOS exceptions (Context Help, Quick Drop, grid alignment); they are written
out below. See SOURCES.md for the keys left out.

    python polyhost/res/overlay_sources/labview/gen_specs.py
    python scripts/generate_app_overlays.py polyhost/res/overlay_sources/labview/bindings.yaml
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[3]))

from polyhost.res.overlay_sources import chord_table  # noqa: E402

AUTO = object()


def k(win, mac=AUTO, linux=AUTO):
    """Keys of one row: Ctrl becomes Cmd on macOS and Alt on Linux unless given."""
    mods, _, key = win.partition("+")
    if mac is AUTO:
        mac = mods.replace("C", "M") + "+" + key
    if linux is AUTO:
        linux = mods.replace("C", "A") + "+" + key
    return {"windows": win, "macos": mac, "linux": linux}


