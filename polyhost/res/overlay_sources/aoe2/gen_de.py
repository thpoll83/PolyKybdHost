#!/usr/bin/env python3
"""Write aoe2_de.yaml (Age of Empires II: Definitive Edition) from aoe2_hd.yaml.

The Definitive Edition uses the HD Edition's keys until it has its own list.
Only the name, the app names it matches, the output file and the ESC mark
(with "D" and "E") differ, so this copies the HD spec and changes those lines.

    python polyhost/res/overlay_sources/aoe2/gen_de.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
CHANGES = {
    "app: aoe2_hd\n": "app: aoe2_de\n",
    "output: aoe2_hd_template\n": "output: aoe2_de_template\n",
    "program_icon: program.png\n": "program_icon: program_de.png\n",
}


def render() -> str:
    """The text of aoe2_de.yaml for the current aoe2_hd.yaml."""
    lines = (HERE / "aoe2_hd.yaml").read_text(encoding="utf-8").splitlines(keepends=True)
    out = ["# GENERATED by gen_de.py from aoe2_hd.yaml -- edit that file, not this one.\n",
           "# Age of Empires II: Definitive Edition. AoE2DE_s.exe on Windows (aoe2de_s),\n",
           "# steam_app_813780 under Proton on KDE Plasma.\n"]
    seen = set()
    for line in lines:
        if line.startswith("match:"):
            line = "match: [aoe2de_s, steam_app_813780]\n"
            seen.add("match")
        elif line in CHANGES:
            seen.add(line)
            line = CHANGES[line]
        out.append(line)
    missing = ({"match"} | set(CHANGES)) - seen
    assert not missing, f"aoe2_hd.yaml no longer has: {missing}"
    return "".join(out)


def main() -> int:
    (HERE / "aoe2_de.yaml").write_text(render(), encoding="utf-8")
    print("aoe2_de.yaml written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
