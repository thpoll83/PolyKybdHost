#!/usr/bin/env python3
"""Write one overlay spec per DaVinci Resolve page from pages.yaml.

    .venv/bin/python polyhost/res/overlay_sources/resolve/gen_pages.py           # write
    .venv/bin/python polyhost/res/overlay_sources/resolve/gen_pages.py --check   # compare only

Each `bindings_<page>.yaml` is pages.yaml's `common` list plus that page's
list, with the placement settings of the fallback spec (bindings.yaml), and
writes `resolve_<page>_template.*`. The page reporter (resolve-plugin/) sends
`resolve://<page>`; the mapping entry routes it to that set. `--check` exits 1
when a generated file differs from what this script would write.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
PAGES = ("media", "cut", "edit", "fusion", "color", "fairlight", "deliver")
# Copied from the fallback spec, so every set places icons the same way.
SETTINGS = ("icon_dir", "fit", "anchor", "region", "margin", "mode", "threshold",
            "program_icon", "program_icon_mode", "program_icon_anchor",
            "program_icon_region", "program_icon_margin")


def _flat(items):
    for it in items:
        if isinstance(it, list):        # a YAML alias of a shared list
            yield from _flat(it)
        else:
            yield it


def _binding(b: dict) -> dict:
    out = {k: v for k, v in b.items() if k != "ref"}
    out["source"] = f"DaVinci Resolve 20 Reference Manual, {b['ref']}"
    return out


def build(page: str, pages: dict, base: dict) -> str:
    spec = {"app": "resolve", "match": ["resolve"],
            "output": f"resolve_{page}_template"}
    for k in SETTINGS:
        spec[k] = base[k]
    bindings = [_binding(b) for b in _flat(pages["common"])]
    bindings += [_binding(b) for b in _flat(pages["pages"][page])]
    seen = {}
    for b in bindings:
        key = (str(b["key"]), tuple(sorted(b["mods"])), tuple(b.get("only", ())))
        if key in seen:
            raise SystemExit(f"{page}: {b['key']} {b['mods']} is bound twice "
                             f"({seen[key]!r} and {b['label']!r})")
        seen[key] = b["label"]
    spec["bindings"] = bindings
    head = (f"# GENERATED by gen_pages.py from pages.yaml -- do not edit.\n"
            f"# DaVinci Resolve, {page.capitalize()} page (resolve://{page}).\n")
    return head + yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=120)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare, write nothing")
    args = ap.parse_args(argv)
    pages = yaml.safe_load((HERE / "pages.yaml").read_text(encoding="utf-8"))
    base = yaml.safe_load((HERE / "bindings.yaml").read_text(encoding="utf-8"))
    stale = []
    for page in PAGES:
        text = build(page, pages, base)
        path = HERE / f"bindings_{page}.yaml"
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(path.name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.name}")
    if stale:
        print("stale: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
