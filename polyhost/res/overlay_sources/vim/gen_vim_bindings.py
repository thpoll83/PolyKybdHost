#!/usr/bin/env python3
"""Write one binding file per Vim mode from `keys.yaml`, and render them.

`keys.yaml` holds Vim's default keys in sections (motions, normal, visual,
insert, replace, cmdline, terminal), taken from `:help index`. A mode's
overlay is a combination of sections:

    normal   = motions + normal
    visual   = motions + visual     (a visual key replaces a motion on the same chord)
    select   = motions + visual + select, without the printable keys
    insert   = insert
    replace  = insert + replace     (a replace key replaces an insert one)
    cmdline  = cmdline
    terminal = terminal

Every set carries Vim's logo on ESC, and every key draws this folder's own
art (`shared: false`, see `bindings_for`). The output is `bindings_<mode>.yaml`
next to this file; `--render` also runs scripts/generate_app_overlays.py on
each (`--preview DIR` writes its review sheets to DIR/<mode>/).

    python polyhost/res/overlay_sources/vim/gen_vim_bindings.py --render --preview /tmp/vim_preview

Deterministic: the same keys.yaml writes byte-identical binding files.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[3]

MODES = {
    "normal": ("motions", "normal"),
    "visual": ("motions", "visual"),
    "select": ("motions", "visual", "select"),
    "insert": ("insert",),
    "replace": ("insert", "replace"),
    "cmdline": ("cmdline",),
    "terminal": ("terminal",),
}

HEADER = """\
# GENERATED by gen_vim_bindings.py from keys.yaml -- edit those, not this file.
# Vim {mode} mode. Shortcut source: `:help index` (runtime/doc/index.txt,
# https://vimhelp.org/index.txt.html); see SOURCES.md.
"""

SPEC = {
    "app": "vim",
    "match": [],
    "icon_dir": "icons",
    "fit": "contain",
    "anchor": "right",
    "region": [40, 40],
    "margin": 0,
    "mode": "alpha",
    "program_icon": "vim.png",
    "program_icon_mode": "luma",
    "program_icon_threshold": 170,
    "program_icon_anchor": "right",
    "program_icon_region": [40, 40],
    "program_icon_margin": 0,
}


# In Select mode a printable key, Enter or Space replaces the selection with
# itself; every other key works as in Visual mode (`:help Select-mode`). So the
# Select set draws no printable key.
PRINTABLE_ONLY = {"select"}


def _printable(b: dict) -> bool:
    key = str(b["key"]).upper()
    typed = len(key) == 1 or key in ("SPACE", "ENTER")
    return typed and set(m.upper() for m in b.get("mods", [])) <= {"SHIFT"}


def _chord(b: dict) -> tuple:
    return (str(b["key"]).upper(), tuple(sorted(m.upper() for m in b.get("mods", []))))


def bindings_for(keys: dict, mode: str) -> list[dict]:
    """The bindings of one mode, later sections replacing earlier chords."""
    merged: dict[tuple, dict] = {}
    for section in MODES[mode]:
        for b in keys[section]:
            merged.pop(_chord(b), None)        # keep the later one's position
            merged[_chord(b)] = b
    out = []
    for b in merged.values():
        if mode in PRINTABLE_ONLY and _printable(b):
            continue
        e = {"key": b["key"]}
        if b.get("mods"):
            e["mods"] = list(b["mods"])
        # shared: false -- every key draws this folder's own 40x40 art, so a
        # picture used in two modes is the same bytes (one pool slot) and the
        # concept renderer cannot swap in its own arrow or trash can for some
        # labels and not others ("Delete (operator)" folds to a trash can).
        e.update({"icon": f"{b['icon']}.png", "label": b["label"], "shared": False,
                  "source": f":help {b['tag']}"})
        out.append(e)
    return out


def write(mode: str, keys: dict) -> Path:
    spec = dict(SPEC, output=f"vim_{mode}_template", bindings=bindings_for(keys, mode))
    path = HERE / f"bindings_{mode}.yaml"
    body = yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=200)
    path.write_text(HEADER.format(mode=mode) + body, encoding="utf-8")
    return path


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--render", action="store_true",
                    help="run generate_app_overlays.py on every binding file")
    ap.add_argument("--preview", type=Path, default=None,
                    help="with --render: write each mode's review sheet under this dir")
    args = ap.parse_args()
    keys = yaml.safe_load((HERE / "keys.yaml").read_text(encoding="utf-8"))
    for mode in MODES:
        path = write(mode, keys)
        print(f"wrote {path.name}")
        if args.render:
            cmd = [sys.executable, str(REPO_ROOT / "scripts" / "generate_app_overlays.py"),
                   str(path)]
            if args.preview:
                cmd += ["--preview", str(args.preview / mode)]
            subprocess.run(cmd, check=True, cwd=REPO_ROOT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
