#!/usr/bin/env python3
"""Write one binding file per evil state from the Vim sets and `evil.yaml`.

Each evil state starts from the Vim set of the same mode
(`../vim/bindings_<mode>.yaml`, written by `../vim/gen_vim_bindings.py`) and
leaves out the keys `evil.yaml` lists under `drop`, the keys that evil's
default keymaps bind differently. Motion state is the Vim Normal set reduced
to the `motions` section of `../vim/keys.yaml` plus `motion_extra`. The icons
are the Vim set's own files (`icon_dir: ../vim/icons`), so a picture costs no
extra overlay slot when Vim and Emacs show it; ESC shows the state word beside
the Emacs logo (`icons/esc_evil_<state>.png`, drawn by `fetch_icons.py`).

    python polyhost/res/overlay_sources/emacs/gen_evil_bindings.py --render \
        --preview /tmp/evil_preview

The output is `evil_<state>.yaml` next to this file. Deterministic: the same
inputs write byte-identical files.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
VIM = HERE.parent / "vim"
REPO_ROOT = HERE.parents[3]

HEADER = """\
# GENERATED by gen_evil_bindings.py from evil.yaml and ../vim/bindings_{vim}.yaml
# -- edit those, not this file. Evil {state} state in GNU Emacs: the Vim keys
# evil binds the same way (evil-maps.el, evil 1.15.0); see SOURCES.md.
"""


def chord(b: dict) -> tuple:
    return (str(b["key"]).upper(), tuple(sorted(str(m).upper() for m in b.get("mods") or [])))


def bindings_for(state: str, evil: dict, vim_keys: dict) -> tuple[list[dict], dict]:
    """The state's bindings, and the Vim spec they came from."""
    vim = evil["states"][state]
    spec = yaml.safe_load((VIM / f"bindings_{vim}.yaml").read_text(encoding="utf-8"))
    drop = {chord(d) for d in evil["drop"] if state in d["states"]}
    labels = {chord(l): l["label"] for l in evil.get("labels", [])}
    keep = None
    if state == "motion":
        keep = {chord(b) for b in vim_keys["motions"]} | {chord(b) for b in evil["motion_extra"]}
    # A drop that names no key of the Vim set is a typo that would leave a
    # wrong key drawn; refuse it.
    unknown = drop - {chord(b) for b in spec["bindings"]}
    if unknown:
        raise SystemExit(f"evil.yaml drops keys not in the Vim {vim} set ({state}): {sorted(unknown)}")
    out = []
    for b in spec["bindings"]:
        c = chord(b)
        if c in drop or (keep is not None and c not in keep):
            continue
        e = dict(b)
        if c in labels:
            e["label"] = labels[c]
        e["source"] = f"{b['source']}; evil-maps.el"
        out.append(e)
    return out, spec


def write(state: str, evil: dict, vim_keys: dict) -> Path:
    bindings, vim_spec = bindings_for(state, evil, vim_keys)
    spec = {k: v for k, v in vim_spec.items() if k != "bindings"}
    spec.update({
        "app": "emacs",
        "icon_dir": "../vim/icons",
        "output": f"emacs_evil_{state}_template",
        "program_icon": f"../../emacs/icons/esc_evil_{state}.png",
        "bindings": bindings,
    })
    path = HERE / f"evil_{state}.yaml"
    body = yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=200)
    path.write_text(HEADER.format(state=state, vim=evil["states"][state]) + body, encoding="utf-8")
    return path


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--render", action="store_true",
                    help="run generate_app_overlays.py on every binding file")
    ap.add_argument("--preview", type=Path, default=None,
                    help="with --render: write each state's review sheet under this dir")
    args = ap.parse_args()
    evil = yaml.safe_load((HERE / "evil.yaml").read_text(encoding="utf-8"))
    vim_keys = yaml.safe_load((VIM / "keys.yaml").read_text(encoding="utf-8"))
    for state in evil["states"]:
        path = write(state, evil, vim_keys)
        print(f"wrote {path.name}")
        if args.render:
            cmd = [sys.executable, str(REPO_ROOT / "scripts" / "generate_app_overlays.py"),
                   str(path)]
            if args.preview:
                cmd += ["--preview", str(args.preview / state)]
            subprocess.run(cmd, check=True, cwd=REPO_ROOT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
