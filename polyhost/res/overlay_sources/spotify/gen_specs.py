#!/usr/bin/env python3
"""Write the Spotify desktop overlay spec from one table.

The keys are the ones Spotify's support article "Spotify keyboard shortcuts"
lists (see SOURCES.md). The article gives one key per action except shuffle,
repeat and the search page, which differ on macOS. Its "Alt" is Option on a
Mac.

Each row: (icon, label, Windows/Linux, macOS). A key is written as modifier
letters and a key name joined by "+": C Ctrl, A Alt (Option on a Mac), S Shift,
M Cmd. None means the platform has no key.

    python polyhost/res/overlay_sources/spotify/gen_specs.py
    python scripts/generate_app_overlays.py polyhost/res/overlay_sources/spotify/bindings.yaml
"""
from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent

MODS = {"C": "CTRL", "A": "ALT", "S": "SHIFT", "M": "GUI"}
KEYS = {",": "COMMA", "/": "SLASH"}

ROWS = [
    ("search", "Open search", "C+K", "M+K"),
    ("searchpage", "Go to search", "C+L", "SM+L"),
    ("help", "Keyboard shortcuts", "C+/", "M+/"),
    ("filter", "Filter", "C+F", "M+F"),
    (None, "Select all", "C+A", "M+A"),
    (None, "Settings", "C+,", "M+,"),
    ("shuffle", "Shuffle", "C+S", "A+S"),
    ("repeat", "Repeat", "C+R", "A+R"),
    ("like", "Like / unlike", "AS+B", "AS+B"),
    ("contextmenu", "Context menu", "A+J", "A+J"),
    ("logout", "Log out", "AS+F6", "AS+F6"),
    ("library", "Your Library", "AS+0", "AS+0"),
    ("playlists", "Playlists", "AS+1", "AS+1"),
    ("podcasts", "Podcasts", "AS+2", "AS+2"),
    ("artists", "Artists", "AS+3", "AS+3"),
    ("albums", "Albums", "AS+4", "AS+4"),
    ("audiobooks", "Audiobooks", "AS+5", "AS+5"),
    ("home", "Home", "AS+H", "AS+H"),
    ("nowplaying", "Now playing", "AS+J", "AS+J"),
    ("liked", "Liked songs", "AS+S", "AS+S"),
    ("madeforyou", "Made for you", "AS+M", "AS+M"),
    ("newreleases", "New releases", "AS+N", "AS+N"),
    ("charts", "Charts", "AS+C", "AS+C"),
    ("queue", "Queue", "AS+Q", "AS+Q"),
    ("npsidebar", "Now playing sidebar", "AS+R", "AS+R"),
    ("libsidebar", "Library sidebar", "AS+L", "AS+L"),
]

HEADER = """\
# Spotify desktop shortcut overlays for PolyKybd.
# GENERATED by gen_specs.py from its table -- edit the table, not this file.
#
# Keys: Spotify Support, "Spotify keyboard shortcuts". See SOURCES.md.
#
# Regenerate:
#   python polyhost/res/overlay_sources/spotify/fetch_icons.py
#   python polyhost/res/overlay_sources/spotify/gen_specs.py
#   python scripts/generate_app_overlays.py \\
#       polyhost/res/overlay_sources/spotify/bindings.yaml --preview /tmp/spotify_preview
app: spotify
match: [spotify]
output: spotify_template
icon_dir: icons
fit: contain
anchor: bottom-right
region: [36, 32]
margin: 0
mode: luma
threshold: 150

program_icon: spotify.png
program_icon_mode: alpha
program_icon_anchor: right
program_icon_region: [37, 32]
program_icon_margin: 0

bindings:
"""


def parse(chord: str) -> tuple[str, list[str]]:
    mods, key = chord.split("+", 1)
    key = KEYS.get(key, key)
    if key.isdigit():
        key = f'"{key}"'
    return key, [MODS[m] for m in mods]


def line(icon, label, chord, mac: bool) -> str:
    key, mods = parse(chord)
    parts = [f"key: {key}", f"mods: [{', '.join(mods)}]"]
    if icon:
        parts.append(f"icon: {icon}.png")
    parts.append(f'label: "{label}"')
    parts.append("only: [macos]" if mac else "except: [macos]")
    return "  - { " + ", ".join(parts) + " }"


def main() -> int:
    out = [HEADER]
    for icon, label, win, mac in ROWS:
        if win:
            out.append(line(icon, label, win, mac=False))
        if mac:
            out.append(line(icon, label, mac, mac=True))
    text = "\n".join(out) + "\n"
    (HERE / "bindings.yaml").write_text(text, encoding="utf-8")
    print(f"bindings.yaml: {text.count(chr(10) + '  - {')} bindings")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
