#!/usr/bin/env python3
"""Write figma_web.yaml, the Figma set for figma.com in a browser tab.

Figma in a browser uses the desktop app's shortcuts, except for the chords the
browser keeps for itself: a page cannot take Ctrl+N, Ctrl+T, Ctrl+W, their Shift
forms or Ctrl+Tab from Chrome (Cmd on macOS). Those keys open or close a
browser window or tab, so the web set leaves them blank. Every other binding is
copied from bindings.yaml unchanged, so the two sets cannot drift.

    python polyhost/res/overlay_sources/figma/gen_web_spec.py          # write
    python polyhost/res/overlay_sources/figma/gen_web_spec.py --check  # exit 1 if stale
    python scripts/generate_app_overlays.py polyhost/res/overlay_sources/figma/figma_web.yaml
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SRC = HERE / "bindings.yaml"
OUT = HERE / "figma_web.yaml"

# Keys the browser keeps under Ctrl (Cmd on macOS), alone or with Shift.
BROWSER_KEYS = {"N", "T", "W", "TAB"}
COMMAND_MODS = {"CMDCTRL", "CTRL", "GUI"}

HEADER = """\
# GENERATED by gen_web_spec.py from bindings.yaml. Do not edit by hand.
# Figma in a browser tab (figma.com/design, /file, /proto): the desktop
# bindings without the chords the browser keeps (Ctrl/Cmd + N, T, W, Tab).
"""


def browser_owned(binding: dict) -> bool:
    """True if the browser handles this chord before the page sees it."""
    mods = {str(m).upper() for m in binding.get("mods") or []}
    if str(binding.get("key")).upper() not in BROWSER_KEYS:
        return False
    return bool(mods & COMMAND_MODS) and mods <= COMMAND_MODS | {"SHIFT"}


def build() -> str:
    spec = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    spec["app"] = "figma (web)"
    spec["match"] = ["figma.com"]
    spec["output"] = "figma_web_template"
    spec["bindings"] = [b for b in spec["bindings"] if not browser_owned(b)]
    body = yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=120)
    return HEADER + body


def main() -> int:
    text = build()
    if "--check" in sys.argv[1:]:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is stale; run {Path(__file__).name}")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
