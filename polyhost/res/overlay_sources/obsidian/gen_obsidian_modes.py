#!/usr/bin/env python3
"""Write Obsidian's per-view binding files from `bindings.yaml`, and render them.

`bindings.yaml` is the editor set (Source mode and Live Preview) and stays the
one place where Obsidian's default hotkeys are written. The Obsidian plugin
(`obsidian-plugin/`) reports which view is active, and the other views use
only part of those keys, or keys of their own:

    global   = the app-wide commands (any other view: PDF, image, settings...)
    reading  = global + the keys that still work in Reading view
    canvas   = global + the Canvas keys (help: "Canvas")
    graph    = global + the Graph view keys (help: "Graph view")
    vim_normal, vim_visual
             = a LAYER drawn over the editor set while Vim key bindings are on:
               the no-modifier and Shift keys of Vim's Normal / Visual mode,
               the ones CodeMirror's Vim emulation implements
               (codemirror_vim_keys.yaml), with the Vim folder's art.

The Vim layers draw no Ctrl key: Obsidian's own Ctrl hotkeys stay on the
board from the editor set underneath. Insert and Replace mode have no layer
(their keys are all Ctrl chords), so they show the editor set.

    python polyhost/res/overlay_sources/obsidian/gen_obsidian_modes.py --render --preview /tmp/obs

Deterministic: the same inputs write byte-identical binding files.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[3]
VIM_DIR = HERE.parent / "vim"

HEADER = """\
# GENERATED by gen_obsidian_modes.py from {inputs} -- edit those, not this file.
# Obsidian, {what}. See SOURCES.md -> "Per-view sets".
"""

# The labels of bindings.yaml that act in every view (app commands).
GLOBAL = ("New note", "Quick switcher", "Command palette", "Graph view", "Close tab",
          "Settings", "Search all files", "Navigate back", "Navigate forward")
# Reading view: no text editing; find, the view toggle and text selection
# still work.
READING = GLOBAL + ("Toggle edit / reading view", "Find in file", "Copy", "Select all")

# Obsidian help, "Canvas" (obsidianmd/obsidian-help en/Plugins/Canvas.md):
# Backspace removes the selection (the macOS "Delete" key is the same key),
# Ctrl/Cmd+A selects all cards, Shift+1 zoom to fit, Shift+2 zoom to
# selection, Ctrl/Cmd+Z undo, Ctrl/Cmd+Y or Ctrl/Cmd+Shift+Z redo.
CANVAS = [
    {"key": "BACKSPACE", "icon": "removecard.png", "label": "Remove selection",
     "source": "Obsidian help: Canvas / ms-fluent/Delete (MIT)"},
    {"key": "1", "mods": ["SHIFT"], "icon": "zoomfit.png", "label": "Zoom to fit",
     "source": "Obsidian help: Canvas / ms-fluent/Zoom Fit (MIT)"},
    {"key": "2", "mods": ["SHIFT"], "icon": "zoomselection.png", "label": "Zoom to selection",
     "source": "Obsidian help: Canvas / ms-fluent/Select Object (MIT)"},
    {"key": "A", "mods": ["CMDCTRL"], "label": "Select all",
     "source": "Obsidian help: Canvas (concept, shared Fluent)"},
    {"key": "Z", "mods": ["CMDCTRL"], "label": "Undo",
     "source": "Obsidian help: Canvas (concept, shared Fluent)"},
    {"key": "Z", "mods": ["CMDCTRL", "SHIFT"], "label": "Redo",
     "source": "Obsidian help: Canvas (concept, shared Fluent)"},
    {"key": "Y", "mods": ["CMDCTRL"], "label": "Redo",
     "source": "Obsidian help: Canvas (concept, shared Fluent)"},
]

# Obsidian help, "Graph view" (en/Plugins/Graph view.md): `+` and `-` zoom,
# the arrow keys move the graph, Shift speeds the movement up. `+` is drawn on
# Shift+= where a US keyboard types it.
GRAPH = [
    {"key": "=", "mods": ["SHIFT"], "icon": "zoomin.png", "label": "Zoom in",
     "source": "Obsidian help: Graph view / ms-fluent/Zoom In (MIT)"},
    {"key": "-", "icon": "zoomout.png", "label": "Zoom out",
     "source": "Obsidian help: Graph view / ms-fluent/Zoom Out (MIT)"},
]
for _mods, _what in (([], "Move graph"), (["SHIFT"], "Move graph faster")):
    for _key, _icon in (("LEFT", "back"), ("RIGHT", "forward"),
                        ("UP", "panup"), ("DOWN", "pandown")):
        GRAPH.append({"key": _key, **({"mods": _mods} if _mods else {}),
                      "icon": f"{_icon}.png", "label": f"{_what} {_key.lower()}",
                      "source": "Obsidian help: Graph view / ms-fluent arrows (MIT)"})

VIEWS = {
    "global": ("every other view (PDF, image, settings, sidebars)", GLOBAL, []),
    "reading": ("Reading view", READING, []),
    "canvas": ("Canvas", GLOBAL, CANVAS),
    "graph": ("Graph view (global and local)", GLOBAL, GRAPH),
}

# --- Vim layers -------------------------------------------------------------

# Vim's keys.yaml sections per mode (as in ../vim/gen_vim_bindings.py).
VIM_MODES = {"normal": ("motions", "normal"), "visual": ("motions", "visual")}

# US keyboard: the character Shift+<key> types.
SHIFTED = dict(zip("1234567890-=[]\\;',./`", "!@#$%^&*()_+{}|:\"<>?~"))
NAMED = {"LEFT": "<Left>", "RIGHT": "<Right>", "UP": "<Up>", "DOWN": "<Down>",
         "BACKSPACE": "<BS>", "SPACE": "<Space>", "DELETE": "<Del>", "HOME": "<Home>",
         "END": "<End>", "PAGEUP": "<PageUp>", "PAGEDOWN": "<PageDown>",
         "ENTER": "<CR>", "INSERT": "<Ins>", "TAB": "<Tab>", "F1": "<F1>"}
# Vim's keys.yaml label that does not fit the emulation.
VIM_LABELS = {("Y", ("SHIFT",)): "Yank line"}

VIM_SPEC = {
    "app": "obsidian",
    "match": [],
    "icon_dir": "../vim/icons",
    "fit": "contain",
    "anchor": "right",
    "region": [40, 40],
    "margin": 0,
    "mode": "alpha",
}


def typed(b: dict) -> str | None:
    """The keystroke a vim binding is, in CodeMirror-vim notation, or None
    for a chord with Ctrl/Alt/GUI (left to Obsidian's set underneath)."""
    mods = {m.upper() for m in b.get("mods", [])}
    if not mods <= {"SHIFT"}:
        return None
    key = str(b["key"]).upper()
    shift = "SHIFT" in mods
    if key in NAMED:
        name = NAMED[key]
        return f"<S-{name[1:]}" if shift else name
    if len(key) != 1:
        return None
    if key.isalpha():
        return key if shift else key.lower()
    return SHIFTED.get(key) if shift else key


def first_keystroke(keys: str) -> str:
    """`gg` -> `g`, `<C-f>` -> `<C-f>`, `f<character>` -> `f`."""
    if keys.startswith("<"):
        end = keys.find(">")
        return keys[:end + 1]
    return keys[0]


def cm_keystrokes(rows: list, mode: str) -> set[str]:
    return {first_keystroke(k) for k, ctx in rows if ctx in ("-", mode)}


def vim_bindings(vim_keys: dict, cm_rows: list, mode: str) -> list[dict]:
    known = cm_keystrokes(cm_rows, mode)
    merged: dict[tuple, dict] = {}
    for section in VIM_MODES[mode]:
        for b in vim_keys[section]:
            chord = (str(b["key"]).upper(), tuple(sorted(m.upper() for m in b.get("mods", []))))
            merged.pop(chord, None)
            merged[chord] = b
    out = []
    for chord, b in merged.items():
        t = typed(b)
        if t is None or t not in known:
            continue
        e = {"key": b["key"]}
        if b.get("mods"):
            e["mods"] = list(b["mods"])
        e.update({"icon": f"{b['icon']}.png", "label": VIM_LABELS.get(chord, b["label"]),
                  "shared": False, "source": f"vim :help {b['tag']}; codemirror-vim {t}"})
        out.append(e)
    return out


# --- writing ----------------------------------------------------------------

def _dump(path: Path, header: str, spec: dict) -> Path:
    body = yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=200)
    path.write_text(header + body, encoding="utf-8")
    return path


def view_spec(base: dict, view: str) -> dict:
    _what, labels, extra = VIEWS[view]
    spec = {k: v for k, v in base.items() if k not in ("bindings", "output", "match")}
    spec["match"] = []
    spec["output"] = f"obsidian_{view}_template"
    spec["bindings"] = [b for b in base["bindings"] if b["label"] in labels] + extra
    return spec


def write_all() -> list[Path]:
    base = yaml.safe_load((HERE / "bindings.yaml").read_text(encoding="utf-8"))
    paths = []
    for view, (what, _l, _e) in VIEWS.items():
        paths.append(_dump(HERE / f"bindings_{view}.yaml",
                           HEADER.format(inputs="bindings.yaml", what=what),
                           view_spec(base, view)))
    vim_keys = yaml.safe_load((VIM_DIR / "keys.yaml").read_text(encoding="utf-8"))
    cm_rows = yaml.safe_load((HERE / "codemirror_vim_keys.yaml").read_text(encoding="utf-8"))["keys"]
    for mode in VIM_MODES:
        spec = dict(VIM_SPEC, output=f"obsidian_vim_{mode}_template",
                    bindings=vim_bindings(vim_keys, cm_rows, mode))
        paths.append(_dump(HERE / f"bindings_vim_{mode}.yaml",
                           HEADER.format(inputs="../vim/keys.yaml and codemirror_vim_keys.yaml",
                                         what=f"Vim {mode} mode layer (drawn over the editor set)"),
                           spec))
    return paths


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--render", action="store_true",
                    help="run generate_app_overlays.py on every binding file")
    ap.add_argument("--preview", type=Path, default=None,
                    help="with --render: write each set's review sheet under this dir")
    args = ap.parse_args()
    for path in write_all():
        print(f"wrote {path.name}")
        if args.render:
            cmd = [sys.executable, str(REPO_ROOT / "scripts" / "generate_app_overlays.py"),
                   str(path)]
            if args.preview:
                cmd += ["--preview", str(args.preview / path.stem)]
            subprocess.run(cmd, check=True, cwd=REPO_ROOT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
